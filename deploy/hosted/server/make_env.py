#!/usr/bin/env python3
"""Generate a server-stand `.env` with fresh random secrets. Never prints a secret value.

Run ON THE SERVER (or any private machine) so the secrets never travel through a chat or a
repository. Refuses to overwrite an existing file; validates every input before creating it.

    python3 make_env.py --example .env.example --output .env \
        --dg-host dg.example.org --speckle-host speckle.example.org \
        --object-host objects.example.org --acme-email ops@example.org
"""
import argparse
import os
from pathlib import Path
import re
import secrets
import sys

LABEL = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
IPV4 = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")

# Fixed, non-secret values for the multi-user server profile.
FIXED = {
    "DG_DEPLOYMENT": "multi-user",
    "DG_COOKIE_SECURE": "true",
    "DG_ALLOW_SELF_REGISTRATION": "false",
    "DG_TRUSTED_PROXIES": "",          # replaced by the edge /32 in docker-compose.hosted.yml
    "SPECKLE_PROJECT_ID": "",
    "SPECKLE_BASE_MODEL_ID": "",
    # Blank falls back to the token saved in the DG UI (Speckle Settings card).
    "SPECKLE_WRITE_TOKEN": "",
    "SPECKLE_READ_TOKEN": "",
    "N8N_USER": "dg-n8n",
    "DG_BOOTSTRAP_ADMIN_USER": "dg-admin",
}
# URL-safe-hex values: they are interpolated into connection strings.
HEX_KEYS = {"POSTGRES_PASSWORD", "NEO4J_PASSWORD", "MINIO_ROOT_PASSWORD"}
TOKEN_KEYS = {"LLM_MASTER_SECRET", "SPECKLE_SESSION_SECRET", "DG_SERVICE_TOKEN", "N8N_PASSWORD"}
SHORT_TOKEN_KEYS = {"DG_BOOTSTRAP_ADMIN_PASSWORD"}   # a person types this once
SPECIAL = {"MINIO_ROOT_USER"}


def fail(message):
    print("make_env: " + message, file=sys.stderr)
    raise SystemExit(2)


def check_host(name, value):
    if not isinstance(value, str) or not value or len(value) > 253:
        fail(f"{name} is not a valid host name")
    labels = value.split(".")
    if len(labels) < 2 or not all(LABEL.match(label) for label in labels):
        fail(f"{name} must be a lowercase DNS name with at least two labels (no scheme, port, path, underscore)")
    if IPV4.match(value) or labels[-1].isdigit():
        fail(f"{name} must be a DNS name, not an IP address")
    return value


def example_keys(path):
    keys = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([A-Z][A-Z0-9_]*)=", line)
        if match:
            keys.append(match.group(1))
    if not keys:
        fail("no keys found in the example file")
    return keys


def value_for(key):
    if key in FIXED:
        return FIXED[key]
    if key in HEX_KEYS:
        return secrets.token_hex(24)
    if key in TOKEN_KEYS:
        return secrets.token_urlsafe(48)
    if key in SHORT_TOKEN_KEYS:
        return secrets.token_urlsafe(18)
    if key == "MINIO_ROOT_USER":
        return "dgminio" + secrets.token_hex(6)
    fail(f"unsupported key in the example file: {key} (add it to make_env.py deliberately)")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--example", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--dg-host", required=True)
    parser.add_argument("--speckle-host", required=True)
    parser.add_argument("--object-host", required=True)
    parser.add_argument("--acme-email", required=True)
    args = parser.parse_args(argv)

    hosts = [check_host("--dg-host", args.dg_host), check_host("--speckle-host", args.speckle_host),
             check_host("--object-host", args.object_host)]
    if len(set(hosts)) != 3:
        fail("the three host names must be distinct")
    if not EMAIL.match(args.acme_email):
        fail("--acme-email is not a valid address")
    output = Path(args.output)
    if output.exists():
        fail("output file already exists; refusing to overwrite")
    keys = example_keys(args.example)

    lines = ["# Generated by deploy/hosted/server/make_env.py. Private; never commit or paste.", ""]
    for key in keys:
        lines.append(f"{key}={value_for(key)}")
    lines += [
        "",
        "# Server edge (docker-compose.hosted.yml + docker-compose.server.yml)",
        f"HOSTED_DG_HOST={hosts[0]}",
        f"HOSTED_SPECKLE_HOST={hosts[1]}",
        f"HOSTED_OBJECT_HOST={hosts[2]}",
        f"HOSTED_ACME_EMAIL={args.acme_email}",
        "HOSTED_EDGE_CIDR=172.30.90.0/28",
        "HOSTED_EDGE_IP=172.30.90.2",
        # Dynamic container addresses come from the upper half so .2 stays free for Caddy.
        "HOSTED_EDGE_DYNAMIC_RANGE=172.30.90.8/29",
        # Required by docker-compose.hosted.yml's interpolation; the server overlay replaces that
        # mount, so nothing is read from this path.
        "HOSTED_EDGE_CERT_DIR=./deploy/hosted/server/unused-certs",
        "",
    ]
    data = "\n".join(lines).encode("utf-8")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    try:
        descriptor = os.open(output, flags, 0o600)
    except FileExistsError:
        fail("output file already exists; refusing to overwrite")
    with os.fdopen(descriptor, "wb") as stream:
        stream.write(data)
    print(f"wrote {output} ({len(keys)} application keys + hosted edge settings); secrets not shown")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
