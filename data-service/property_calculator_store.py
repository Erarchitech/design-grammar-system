"""Stored property calculators per project DataProperty (Phase 1303-15, experimental).

A calculator, once resolved from the catalogue or generated by the LLM, is stored as
``(:DatatypeProperty {iri, project})-[:COMPUTED_BY]->(:PropertyCalculator {project, dataPropertyIri, ...})`` and
reused on every later generation, so a rule update or a new Design State re-runs the same script and the LLM is
asked once per property. A changed threshold needs no new script (VALIDATOR re-reads the rule); a rule over a new
DataProperty adds one calculator. ``status = 'rejected'`` takes a calculator out of use without deleting its history.

Phase 1303-16 (D-54..D-60) adds the review lifecycle of a generated calculator: pending, confirmed (promoted into
the company catalogue as a ``CatalogueCalculator``), rejected (durable: the rejected sha256 is remembered even after
a regenerated source made the row active again), retired (paused for the whole company) and confirmed again.
"""

from __future__ import annotations

import hashlib
import json
import logging
import threading
from datetime import datetime, timezone
from typing import Any

logger = logging.getLogger(__name__)

CATALOGUE_LABEL = "CatalogueCalculator"
CATALOGUE_GRAPH = "CalculatorCatalogue"
STATUS_ACTIVE = "active"
STATUS_REJECTED = "rejected"
STATUS_RETIRED = "retired"
REVIEW_PENDING = "pending"
REVIEW_CONFIRMED = "confirmed"
REVIEW_REJECTED = "rejected"

# Single-worker idiom of auth._STORE_LOCK (the data-service runs one uvicorn worker): confirm and retire of the
# company catalogue run one at a time inside this process; the row write lock (reviewLock) and MERGE on catalogueId
# protect the graph itself.
_CATALOGUE_LOCK = threading.Lock()


class CalculatorReviewError(Exception):
    """A review refusal with a stable ``code`` and an HTTP ``status`` for the route layer (plan 1303-17)."""

    def __init__(self, code: str, status: int, detail: str):
        super().__init__(f"{code}: {detail}")
        self.code = code
        self.status = status
        self.detail = detail


LOAD_QUERY = (
    "MATCH (pc:PropertyCalculator {project:$project}) WHERE coalesce(pc.status, 'active') = 'active' "
    "RETURN pc.dataPropertyIri AS dataPropertyIri, pc.calculator AS calculator, pc.origin AS origin, "
    "pc.paramsJson AS paramsJson, pc.function AS function, pc.source AS source, pc.sha256 AS sha256, "
    "pc.provider AS provider, pc.model AS model, pc.createdAt AS createdAt, pc.createdBy AS createdBy, "
    "pc.unit AS unit, pc.explanation AS explanation, pc.catalogueId AS catalogueId, "
    "pc.reviewStatus AS reviewStatus "
    "ORDER BY dataPropertyIri"
)

# Row write lock and state read in one statement: the reviewLock increment makes concurrent writers of the same
# row queue, and the returned state is what the save decides on. It also returns rejectedSha256Json, the list of
# every source the project rejected for this DataProperty (never written by a save).
SAVE_STATE_QUERY = (
    "MERGE (pc:PropertyCalculator {project:$project, dataPropertyIri:$dataPropertyIri}) "
    "SET pc.reviewLock = coalesce(pc.reviewLock, 0) + 1 "
    "RETURN pc.dataPropertyIri AS dataPropertyIri, pc.sha256 AS sha256, pc.status AS status, "
    "pc.reviewStatus AS reviewStatus, pc.catalogueId AS catalogueId, pc.createdAt AS createdAt, "
    "pc.createdBy AS createdBy, pc.regenerateRequested AS regenerateRequested, "
    "pc.rejectedSha256Json AS rejectedSha256Json"
)

# The review state (status, reviewStatus, catalogueId, regenerateRequested, createdAt, createdBy) is computed in
# Python from SAVE_STATE_QUERY and written as given; this statement never writes the rejected-hash list.
SAVE_QUERY = (
    "MERGE (pc:PropertyCalculator {project:$project, dataPropertyIri:$dataPropertyIri}) "
    "SET pc.calculator = $calculator, pc.origin = $origin, pc.paramsJson = $paramsJson, pc.function = $function, "
    "pc.source = $source, pc.sha256 = $sha256, pc.provider = $provider, pc.model = $model, "
    "pc.unit = $unit, pc.explanation = $explanation, "
    "pc.createdAt = $createdAt, pc.createdBy = $createdBy, pc.status = $status, "
    "pc.reviewStatus = $reviewStatus, pc.catalogueId = $catalogueId, "
    "pc.regenerateRequested = $regenerateRequested, pc.graph = 'Computgraph' "
    "WITH pc "
    "OPTIONAL MATCH (d:DatatypeProperty {iri:$dataPropertyIri, project:$project}) "
    "FOREACH (_ IN CASE WHEN d IS NULL THEN [] ELSE [1] END | MERGE (d)-[:COMPUTED_BY]->(pc)) "
    "RETURN pc.dataPropertyIri AS dataPropertyIri"
)

# Every row that is not simply the active, never-rejected current calculator: rejected or retired rows, and active
# rows that still remember an earlier rejection (a regenerated source made them active again). No origin filter: a
# rejection list must stay visible even if a catalogue binding later replaced the generated source.
BLOCKED_QUERY = (
    "MATCH (pc:PropertyCalculator {project:$project}) "
    "WHERE (pc.status IN ['rejected', 'retired'] "
    "OR (pc.rejectedSha256Json IS NOT NULL AND pc.rejectedSha256Json <> '[]')) "
    "RETURN pc.dataPropertyIri AS dataPropertyIri, pc.status AS status, pc.sha256 AS sha256, "
    "pc.rejectedSha256Json AS rejectedSha256Json, pc.reviewReason AS reviewReason, "
    "pc.reviewedBy AS reviewedBy, pc.regenerateRequested AS regenerateRequested "
    "ORDER BY dataPropertyIri"
)


# A context class (Beam, Column, Wall, ...) is matched by project + label so a class the user or the rule ingest
# already created is reused, never duplicated; DG adds the Revit categories it stands for and links the calculator.
CONTEXT_CLASS_QUERY = (
    "MERGE (k:Class {project:$project, label:$label}) "
    "ON CREATE SET k.iri = $iri, k.graph = 'OntoGraph', k.source = 'property_scripts' "
    "SET k.revitCategories = [x IN coalesce(k.revitCategories, []) WHERE NOT x IN $categories] + $categories "
    "WITH k "
    "MATCH (pc:PropertyCalculator {project:$project, dataPropertyIri:$dataPropertyIri}) "
    "MERGE (pc)-[r:READS_CLASS]->(k) SET r.revitCategories = $categories "
    "RETURN k.iri AS iri"
)


UNLINK_QUERY = (
    "MATCH (pc:PropertyCalculator {project:$project, dataPropertyIri:$dataPropertyIri})-[r:READS_CLASS]->(k:Class) "
    "WHERE NOT k.label IN $keep DELETE r"
)
# A context class DG created that nothing uses any more (no rule atom, calculator, object, profile...) goes away.
PRUNE_QUERY = (
    "MATCH (k:Class {project:$project, source:'property_scripts'}) WHERE NOT (k)--() "
    "WITH k, k.label AS label DELETE k RETURN label ORDER BY label"
)


def save_context_classes(session: Any, project: str, data_property_iri: str, classes: list[dict]) -> None:
    """Link the calculator to exactly ``classes``: stale READS_CLASS edges (a catalogue fix dropped a category)
    are removed first, then the current classes are matched or created and linked."""
    import class_duplicates

    # A class of the same concept that the project already has (Slab for Floor, Hole for Opening) is used instead
    # of a new one: DG never adds a duplicate itself.
    existing = [r["label"] for r in session.run(
        "MATCH (k:Class {project:$project}) RETURN coalesce(k.label, k.iri) AS label ORDER BY label",
        project=project).data()]
    reused = []
    for c in classes:
        same = next((e for e in existing if e != c["label"]
                     and (class_duplicates.class_reason(c["label"], e) or "").startswith("same concept")), None)
        reused.append({**c, "label": same} if same else c)
    classes = reused
    session.run(UNLINK_QUERY, project=project, dataPropertyIri=data_property_iri,
                keep=[c["label"] for c in classes]).consume()
    for c in classes:
        session.run(CONTEXT_CLASS_QUERY, project=project, label=c["label"], iri=c["iri"],
                    categories=list(c["revitCategories"]), dataPropertyIri=data_property_iri).consume()


def prune_context_classes(session: Any, project: str) -> list[str]:
    return [r["label"] for r in session.run(PRUNE_QUERY, project=project).data()]


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def property_key(iri: str) -> str:
    """The company-wide key of a DataProperty: its lower-cased local name (hasHeightMm -> hasheightmm)."""
    import property_scripts

    return property_scripts.local_name(iri).lower()


def catalogue_id(company: str, sha256: str) -> str:
    """``CC-`` + the first 16 hex of sha256(company + U+001F + sha256): one entry per company and source."""
    return "CC-" + hashlib.sha256(f"{company}\x1f{sha256}".encode("utf-8")).hexdigest()[:16]


def company_of(project: str) -> str | None:
    """The company of a project, or None. Fails closed: any error means no shared rows."""
    try:
        import company

        return company.company_for_project(project)
    except Exception:  # noqa: BLE001 - an unreadable company store must never widen access
        return None


def created_after(later_iso: Any, earlier_iso: Any) -> bool:
    """True when ``later_iso`` is strictly later than ``earlier_iso`` (ISO-8601, trailing Z or offset).
    A missing or unparsable value gives False."""

    def parse(value: Any) -> datetime | None:
        if not isinstance(value, str) or not value.strip():
            return None
        try:
            moment = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
        except ValueError:
            return None
        return moment if moment.tzinfo else moment.replace(tzinfo=timezone.utc)

    later, earlier = parse(later_iso), parse(earlier_iso)
    return later is not None and earlier is not None and later > earlier


def is_blocked(entry: dict | None) -> bool:
    """A rejected or retired calculator with no regenerate request: nothing may bind for the property."""
    return bool(entry) and entry.get("status") in (STATUS_REJECTED, STATUS_RETIRED) and not entry.get("regenerate")


def rejected_source(blocked: dict[str, dict], iri: str, sha256: str | None) -> bool:
    """True when the project rejected exactly this source for this DataProperty (D-54 point 4)."""
    return bool(sha256) and sha256 in ((blocked or {}).get(iri) or {}).get("sha256s", [])


def _hash_list(raw: Any) -> list[str]:
    try:
        value = json.loads(raw) if isinstance(raw, str) and raw else []
    except ValueError:
        return []
    return [h for h in value if isinstance(h, str)] if isinstance(value, list) else []


def load_active(session: Any, project: str) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for row in session.run(LOAD_QUERY, project=project).data():
        row = dict(row)
        row["params"] = json.loads(row.pop("paramsJson") or "{}")
        if row.get("origin") == "generated" and not row.get("reviewStatus"):
            row["reviewStatus"] = REVIEW_PENDING
        out[row["dataPropertyIri"]] = row
    return out


def load_blocked(session: Any, project: str) -> dict[str, dict]:
    """Per DataProperty IRI: every source hash the project rejected, plus the state of a rejected or retired row.

    ``sha256`` is the row's current hash (the UI regenerate action sends it back). ``sha256s`` is what is
    rejected: for a rejected row the earlier hashes and the current one; for a retired or active row only the
    earlier hashes, because the current hash of a retired row is paused, not rejected (D-59)."""
    out: dict[str, dict] = {}
    for row in session.run(BLOCKED_QUERY, project=project).data():
        iri = row.get("dataPropertyIri")
        if not iri:
            continue
        status = row.get("status")
        hashes = set(_hash_list(row.get("rejectedSha256Json")))
        if status not in (STATUS_REJECTED, STATUS_RETIRED) and not hashes:
            continue
        if status == STATUS_REJECTED and row.get("sha256"):
            hashes.add(row["sha256"])
        out[iri] = {
            "status": status,
            "sha256": row.get("sha256"),
            "sha256s": sorted(hashes),
            "reason": row.get("reviewReason"),
            "by": row.get("reviewedBy"),
            "regenerate": bool(row.get("regenerateRequested")),
        }
    return out


def _save_tx(tx: Any, project: str, entry: dict, actor: str | None) -> dict:
    iri = entry["dataPropertyIri"]
    state = next((r for r in tx.run(SAVE_STATE_QUERY, project=project, dataPropertyIri=iri).data()
                  if r.get("dataPropertyIri") == iri), None) or {}
    sha256 = entry.get("sha256")
    generated = entry.get("origin") == "generated"
    if generated and sha256 and sha256 in _hash_list(state.get("rejectedSha256Json")):
        logger.warning("property calculator save refused: source already rejected for %s", iri)
        return {"saved": False, "reason": "rejected source"}
    same = bool(state.get("sha256")) and state.get("sha256") == sha256
    default_review = REVIEW_PENDING if generated else None
    if same and state.get("reviewStatus"):
        review_status = state["reviewStatus"]
    else:
        review_status = entry.get("reviewStatus", default_review)
    tx.run(
        SAVE_QUERY,
        project=project,
        dataPropertyIri=iri,
        calculator=entry["calculator"],
        origin=entry["origin"],
        paramsJson=json.dumps(entry.get("params") or {}, sort_keys=True),
        function=entry.get("function"),
        source=entry.get("source"),
        sha256=sha256,
        provider=entry.get("provider"),
        model=entry.get("model"),
        unit=entry.get("unit"),
        explanation=entry.get("explanation"),
        createdAt=(state.get("createdAt") if same and state.get("createdAt") else utc_now()),
        createdBy=(state.get("createdBy") if same and state.get("createdBy") else actor),
        status=((state.get("status") or STATUS_ACTIVE) if same else STATUS_ACTIVE),
        reviewStatus=review_status,
        catalogueId=entry.get("catalogueId") or (state.get("catalogueId") if same else None),
        regenerateRequested=(bool(state.get("regenerateRequested")) if same else False),
    ).consume()
    return {"saved": True, "reason": None}


def save(session: Any, project: str, entry: dict, actor: str | None) -> dict:
    """Store a calculator without ever undoing a review decision: an unchanged sha256 keeps status, review state,
    catalogueId and authorship (a rejected calculator stays rejected through every later save); a different
    sha256 starts again as active and pending. A generated source the project already rejected is not stored."""
    return session.execute_write(_save_tx, project, entry, actor)
