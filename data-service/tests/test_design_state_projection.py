"""Tests for design_state_projection.py (Phase 1202 Plan 02, ALGN12-08/ALGN12-09).

Cross-language parity twin: DG/tests/DG.Tests/DesignStateCanonicalProjectionTests.cs's
ComputeHash_ShouldMatchSharedCrossLanguageVector Fact. Both suites assert the SAME hard-coded
64-char uppercase hex constant for the equivalent input -- a divergence in either language fails
that language's test before any DE-01 cross-leg comparison could report it (the CR-01/WR-01
precedent, 1202-CONTEXT.md T-1202-04).
"""
import copy
