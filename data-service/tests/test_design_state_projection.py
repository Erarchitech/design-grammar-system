from design_state_projection import build_projection, compute_state_hash

# Twin of DG/tests/DG.Tests/DesignStateCanonicalProjectionTests.cs's SharedVectorHash constant,
# generated by actually running DesignStateCanonicalProjection.ComputeHash against the equivalent
# fixed DesignState (see 1202-02-SUMMARY.md) -- not guessed independently on this side.
SHARED_VECTOR_HASH = "4A4CAB67B35F6F9B3A0E42BA56C5A366673675CBC871DFA302058977CC34E09E"


def _repo_root() -> Path:
    mnt = Path("/mnt/repo")
    if mnt.exists():
        return mnt
    return Path(__file__).resolve().parent.parent.parent


