def test_build_projection_members_manifest_lists_every_member_sorted():
    payload = _shared_vector_payload()

    projection = build_projection(payload)
    members = projection["members"]

    assert len(members) == 4
    kinds = [m["kind"] for m in members]
    assert kinds == sorted(kinds)
    assert {"kind": "objState", "stateId": "OS_1202_A"} in members
    assert {"kind": "objState", "stateId": "OS_1202_B"} in members
    assert {"kind": "paramState", "stateId": "DS_1202_PARAMS_01"} in members
    assert {"kind": "propState", "stateId": "PS_1202_HEIGHT_01"} in members


def test_build_projection_converts_number_parameter_to_decimal():
    payload = _shared_vector_payload()

    projection = build_projection(payload)
    parameter_value = projection["paramStates"][0]["parameters"][0]["value"]

    assert isinstance(parameter_value, Decimal)
    assert parameter_value == Decimal("42.0") or parameter_value == Decimal("42")


def test_serializer_never_calls_hashlib_directly():
    """Grep-verifiable acceptance criterion: no second hasher.

    Mirrors the plan's own acceptance check
    (``grep -v '^\\s*#' data-service/design_state_projection.py | grep -cE 'hashlib|sha256'``
    returns 0) rather than a line-by-line scan here, so prose in the module docstring that
    merely *mentions* hashlib/sha256 (to explain why they must not appear in code) cannot
    trip this test the way a naive per-line substring scan would.
    """
    module_path = Path(__file__).resolve().parent.parent / "design_state_projection.py"
    code_lines = [
        line for line in module_path.read_text(encoding="utf-8").splitlines()
        if not line.strip().startswith("#")
    ]
    code_only = "\n".join(code_lines)
    assert "import hashlib" not in code_only
    assert "hashlib." not in code_only
    assert "sha256(" not in code_only
    assert "hash_canonical" in code_only


def test_fixture_expected_canonical_state_hash_is_populated():
    fixture_path = _repo_root() / "fixtures" / "golden" / "replay" / "mixed-verdicts.json"
    with open(fixture_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    digest = data["expectedCanonicalStateHash"]
    assert isinstance(digest, str)
    assert len(digest) == 64
    assert digest == digest.upper()
    assert data["canonicalizationVersion"] == 1


def test_fixture_canonical_state_hash_is_independently_reproducible():
    """Recompute the fixture's own canonicalStateHash from its embedded statePayloadJson rather
    than trusting the recorded literal -- the CR-01/WR-01 double-check discipline.
    """
    fixture_path = _repo_root() / "fixtures" / "golden" / "replay" / "mixed-verdicts.json"
    with open(fixture_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    payload = json.loads(data["statePayloadJson"], parse_float=Decimal)
    recomputed = compute_state_hash(payload)

    assert recomputed == data["expectedCanonicalStateHash"]
